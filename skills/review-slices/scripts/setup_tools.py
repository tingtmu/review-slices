import os
import subprocess
import sys
import tempfile

GUARD = ".githooks/review_slices.py"
OVERRIDE = "If the user decides to push anyway, the user runs `git push --no-verify`; an agent never does."


def git(*args):
    done = subprocess.run(("git",) + args, capture_output=True, text=True)
    return done.stdout if done.returncode == 0 else None


def find_guard():
    """(source, problem, adopted): the base branch's guard, or why the push must stop, and whether the base branch
    has review rules. No source and no problem means run the checkout's guard."""
    base = (git("config", "--get", "review-slices.base") or "").strip()
    if base and git("rev-parse", "--verify", "--quiet", "refs/remotes/%s^{commit}" % base):
        source = git("show", "refs/remotes/%s:%s" % (base, GUARD))
        adopted = "```review-slices" in (git("show", "refs/remotes/%s:REVIEW.md" % base) or "")
        if source:
            return source, None, adopted
        removed = (git("log", "-1", "--format=%H", "--diff-filter=D", "refs/remotes/" + base, "--", GUARD)
                   or "").strip()
        if removed:
            print("review-slices: the base branch %s lost %s in %s, so the last guard it had runs; restore it there"
                  % (base, GUARD, removed[:12]), file=sys.stderr)
            return git("show", "%s^:%s" % (removed, GUARD)), None, adopted
        return None, None, adopted  # adoption: the guard was never on the base branch
    remote = base.split("/", 1)[0] if base else "origin"
    if (git("for-each-ref", "--count=1", "refs/remotes/%s/" % remote) or "").strip():
        return None, ("the base branch %s is not in this clone: fetch it, or fix `git config review-slices.base`"
                      % (base or "(not set)")), False
    return None, None, False  # a first push: the remote has nothing yet


def run(path, args, data):
    env = dict(os.environ, REVIEW_SLICES_HANDOFF="1")
    return subprocess.run([sys.executable, path] + args, input=data, env=env).returncode


def main(args):
    data = sys.stdin.buffer.read()
    source, problem, adopted = find_guard()
    if problem:
        print("review-slices refused the push: %s\\n%s" % (problem, OVERRIDE), file=sys.stderr)
        return 1
    if source is None:
        path = os.path.join((git("rev-parse", "--show-toplevel") or "").strip(), GUARD)
        if not os.path.isfile(path):
            if adopted:
                print("review-slices refused the push: neither the base branch nor this checkout has %s\\n%s"
                      % (GUARD, OVERRIDE), file=sys.stderr)
                return 1
            print("review-slices: no guard on the base branch or in this checkout, so this push is not checked",
                  file=sys.stderr)
            return 0
        if not adopted:
            print("review-slices: the base branch has no guard yet, so this checkout's guard runs", file=sys.stderr)
        return run(path, args, data)
    with tempfile.TemporaryDirectory() as tmp:
        path = os.path.join(tmp, "review_slices.py")
        with open(path, "w", encoding="utf-8") as handle:
            handle.write(source)
        return run(path, args, data)


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
