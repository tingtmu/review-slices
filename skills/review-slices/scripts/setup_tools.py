def load(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


guard = load("review_slices", SKILL_GUARD)
scanner = load("secret_scan", SKILL_SCANNER)
git = guard.git


def wants_scanner(root):
    """Whether the working REVIEW.md says `secrets:`, so the repo needs the secret scan beside the guard."""
    return bool((guard.working_config(root) or {}).get("secrets"))


def read(path):
    try:
        with open(path, encoding="utf-8", errors="replace") as handle:
            return handle.read()
    except FileNotFoundError:
        return None


def write(path, text, mode=0o644):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as handle:
        handle.write(text)
    os.chmod(path, mode)


def paths():
    root = git("rev-parse", "--show-toplevel")
    common = git("rev-parse", "--path-format=absolute", "--git-common-dir")
    return root, common, os.path.join(common, "review-slices", "bootstrap.py")


def resolve_base(root):
    """(name, why): the base branch's remote-tracking name (e.g. origin/main) and why install chose it; (None, None)
    if none is fetched. In order: REVIEW.md's base on the `upstream` remote when it is a fork's canonical repo with
    review rules; on its tracking remote when that is origin or has review rules; on origin; origin's default
    branch. Any other remote without rules never judges, since the checkout's own guard would run in its place."""
    config = guard.working_config(root)
    default = git("symbolic-ref", "--short", "--quiet", "refs/remotes/origin/HEAD", check=False)
    branch = (config or {}).get("base") or (default.split("/", 1)[-1] if default else "main")
    remote = git("config", "--get", "branch.%s.remote" % branch, check=False) or "origin"
    tracking, on_origin = "%s/%s" % (remote, branch), "origin/" + branch
    if remote == "upstream" or (remote != "origin" and guard.rules_at("refs/remotes/" + tracking) is None):
        tracking = None
    own = tracking if fetched(tracking) else on_origin
    for name, why in ((canonical_upstream(branch, own), "the canonical repo, which has review rules"),
                      (tracking, "the base branch on its tracking remote"),
                      (on_origin, "the base branch on origin"),
                      (default, "origin's default branch")):
        if fetched(name):
            return name, why
    return None, None


def fetched(name):
    """Whether NAME (e.g. origin/main) is a fetched remote-tracking branch."""
    return bool(name and git("rev-parse", "--verify", "--quiet", "refs/remotes/%s^{commit}" % name, check=False))


def canonical_upstream(branch, own):
    """`upstream/BRANCH` when a fork's canonical repo has adopted review-slices and already contains OWN, the fork's
    own base branch (if fetched); None otherwise, so a canonical repo without rules never becomes the judge."""
    name = "upstream/" + branch
    if guard.rules_at("refs/remotes/" + name) is None:
        return None
    if not fetched(own):
        return name
    contained = git("merge-base", "--is-ancestor", "refs/remotes/" + own, "refs/remotes/" + name, check=False)
    return name if contained is not None else None


def hook_file_steps(hooks, bootstrap):
    """Steps that wire a pre-push hook file in HOOKS to the bootstrap, keeping any hook already there."""
    pre_push = os.path.join(hooks, "pre-push")
    wrapper = WRAPPER % (shlex.quote(bootstrap), CHAINED)
    existing = read(pre_push)
    if existing == wrapper:
        return [], []
    if existing is None or WRAPPER_MARK in existing:
        return [("write %s, which runs the bootstrap" % pre_push, lambda: write(pre_push, wrapper, 0o755))], []
    if PRE_COMMIT_MARK in existing:
        legacy = pre_push + ".legacy"
        current = read(legacy)
        if current == wrapper:
            return [], []
        if current is not None and WRAPPER_MARK not in current:
            return [], ["pre-commit manages %s and its .legacy hook is taken; ask the user how to chain them"
                        % pre_push]
        return [("write %s, which pre-commit runs first with the full push input" % legacy,
                 lambda: write(legacy, wrapper, 0o755))], []
    chained = os.path.join(hooks, CHAINED)
    if os.path.exists(chained):
        return [], ["%s exists beside a pre-push hook that is not ours; ask the user" % chained]

    def chain():
        shutil.move(pre_push, chained)
        write(pre_push, wrapper, 0o755)
    return [("move the existing pre-push hook to %s and write a pre-push that runs the guard, then it, each with "
             "the full push input" % chained, chain)], []


def agent_hook_entries(text):
    """(settings, PreToolUse entries) of a hook settings file's TEXT; ValueError if it is not JSON of the shape
    Claude Code and Codex read: an object whose "hooks" maps events to lists of {"hooks": [...]} objects."""
    data = json.loads(text) if text else {}
    hooks = data.get("hooks", {}) if isinstance(data, dict) else None
    entries = hooks.get("PreToolUse", []) if isinstance(hooks, dict) else None
    if not isinstance(entries, list) or not all(isinstance(entry, dict) and isinstance(entry.get("hooks", []), list)
                                                and all(isinstance(hook, dict) for hook in entry.get("hooks", []))
                                                for entry in entries):
        raise ValueError("not a hook settings object")
    return data, entries


def has_agent_hook(entries):
    return any(hook.get("command") == AGENT_COMMAND for entry in entries for hook in entry.get("hooks", []))


def without_old_agent_hooks(entries):
    """ENTRIES without earlier versions of the review-slices agent hook, so install replaces rather than adds."""
    kept = [dict(entry, hooks=[hook for hook in entry.get("hooks", [])
                               if AGENT_HOOK_PATH not in hook.get("command", "")])
            for entry in entries]
    return [entry for entry in kept if entry["hooks"]]


def agent_hook_steps(root):
    """Steps that add the agent hook to Claude Code's and Codex's committed hook settings, keeping what is there."""
    steps, problems = [], []
    if read(os.path.join(root, AGENT_HOOK_PATH)) is None:
        steps.append(("copy the skill's agent hook to %s; commit it" % AGENT_HOOK_PATH,
                      lambda: write(os.path.join(root, AGENT_HOOK_PATH), read(SKILL_AGENT_HOOK), 0o755)))
    for relative, matcher in AGENT_SETTINGS:
        path = os.path.join(root, relative)
        try:
            data, entries = agent_hook_entries(read(path))
        except ValueError:
            problems.append("%s is not valid JSON; add the agent hook to it by hand" % relative)
            continue
        if has_agent_hook(entries):
            continue
        entry = {"matcher": matcher, "hooks": [{"type": "command", "command": AGENT_COMMAND, "timeout": 10}]}
        merged = dict(data, hooks=dict(data.get("hooks", {}), PreToolUse=without_old_agent_hooks(entries) + [entry]))
        steps.append(("add the review-slices agent hook to %s; commit it (it does nothing in a clone that never "
                      "ran install)" % relative,
                      lambda path=path, merged=merged: write(path, json.dumps(merged, indent=2) + "\n")))
    return steps, problems


def install_steps(config_hook=False, agent_hooks=False):
    """(steps, problems): the (description, action) pairs `install` would carry out, and what blocks it."""
    root, common, bootstrap = paths()
    steps, problems = [], []
    if not os.path.exists(os.path.join(root, guard.GUARD_PATH)):
        steps.append(("copy the skill's guard %s to %s; commit it as a reviewed change" % (guard.VERSION,
                      guard.GUARD_PATH), lambda: write(os.path.join(root, guard.GUARD_PATH), read(SKILL_GUARD), 0o755)))
    if not os.path.exists(os.path.join(root, guard.MERGED_PATH)):
        steps.append(("copy the skill's merged-reviewer measure to %s; commit it with the guard" % guard.MERGED_PATH,
                      lambda: write(os.path.join(root, guard.MERGED_PATH), read(SKILL_MERGED), 0o755)))
    if wants_scanner(root) and not os.path.exists(os.path.join(root, guard.SCANNER_PATH)):
        steps.append(("copy the skill's secret scan to %s (REVIEW.md says secrets:); commit it with the guard"
                      % guard.SCANNER_PATH, lambda: write(os.path.join(root, guard.SCANNER_PATH), read(SKILL_SCANNER),
                                                          0o755)))
    if read(bootstrap) != BOOTSTRAP:
        steps.append(("write %s, which runs the guard committed on the base branch" % bootstrap,
                      lambda: write(bootstrap, BOOTSTRAP, 0o755)))
    base, why = resolve_base(root)
    if base is None:
        problems.append("no remote-tracking base branch: fetch, then run install again (a first push is fine)")
    elif git("config", "--get", "review-slices.base", check=False) != base:
        steps.append(("set review-slices.base to %s (%s)" % (base, why),
                      lambda: git("config", "review-slices.base", base)))
    hooks_path = git("config", "--get", "core.hooksPath", check=False)
    if git("config", "--local", "--get", "core.hooksPath", check=False) == ".githooks":
        steps.append(("unset core.hooksPath=.githooks (0.1.0's install), so the hooks in .git/hooks run again",
                      lambda: git("config", "--local", "--unset", "core.hooksPath")))
        hooks_path = None
    command = "python3 %s pre-push" % shlex.quote(bootstrap)
    if config_hook or (hooks_path and guard.git_version() >= (2, 54)):
        if guard.git_version() < (2, 54):
            return steps, problems + ["this git (%s) does not run config hooks" % ".".join(
                map(str, guard.git_version()))]
        if (git("config", "--get", "hook.review-slices.command", check=False) != command
                or "pre-push" not in (git("config", "--get-all", "hook.review-slices.event", check=False) or "")):
            steps.append(("register the config hook review-slices for pre-push: %s" % command, lambda: (
                git("config", "--replace-all", "hook.review-slices.event", "pre-push"),
                git("config", "hook.review-slices.command", command))))
    elif hooks_path:
        problems.append("core.hooksPath is %s, so a hook file would go where another tool manages hooks, and this "
                        "git is older than 2.54, which config hooks need; ask the user" % hooks_path)
    else:
        more_steps, more_problems = hook_file_steps(os.path.join(common, "hooks"), bootstrap)
        steps, problems = steps + more_steps, problems + more_problems
    if agent_hooks:
        more_steps, more_problems = agent_hook_steps(root)
        steps, problems = steps + more_steps, problems + more_problems
    return steps, problems


def cmd_install(args):
    steps, problems = install_steps("--config-hook" in args, "--agent-hooks" in args)
    apply = "--apply" in args
    print("review-slices install%s:" % ("" if apply else " (dry run; add --apply to make these changes)"))
    for number, (description, action) in enumerate(steps, 1):
        print("  %d. %s" % (number, description))
        if apply:
            action()
    if not steps:
        print("  nothing to change")
    for problem in problems:
        print("problem: " + problem)
    if apply:
        print()
        return max(cmd_doctor([]), 1 if problems else 0)
    return 1 if problems else 0


def cmd_upgrade(args):
    """Copy this skill's scripts over the repo's copies in .githooks/: the guard always, the agent hook and the
    incident report only where the repo already has them, the secret scan also where REVIEW.md says secrets:."""
    root, _common, _bootstrap = paths()
    current = read(os.path.join(root, guard.GUARD_PATH))
    if current is None:
        print("no %s here: run install first" % guard.GUARD_PATH)
        return 1
    have = guard.source_version(current)
    if have > guard.version_tuple(guard.VERSION):
        print("the repo's guard (%s) is newer than this skill's (%s): update the skill instead" % (
            ".".join(map(str, have)), guard.VERSION))
        return 1
    copies = [(source, os.path.join(root, ".githooks", os.path.basename(source))) for source in COPIED]
    stale = [(source, copy) for source, copy in copies if read(copy) not in (None, read(source))
             or (read(copy) is None and (source == SKILL_MERGED or source == SKILL_SCANNER and wants_scanner(root)))]
    if not stale:
        print("the repo's copies are this skill's (%s)" % guard.VERSION)
        return 0
    for source, copy in stale:
        print("copy this skill's %s (%s) over %s%s" % (os.path.basename(source), guard.VERSION,
                                                       os.path.relpath(copy, root),
                                                       "" if "--apply" in args else "; add --apply to do it"))
        if "--apply" in args:
            write(copy, read(source), 0o755)
    print("then commit them as a reviewed change (REVIEW.md puts .githooks/ at important or higher); the guard "
          "judges pushes once it is on the base branch")
    if os.path.exists(os.path.join(root, ".githooks", "pre-push")):
        print("also delete .githooks/pre-push (0.1.0's hook) in that commit, once every clone has run install")
    return 0


def tree_lines(root, bootstrap, base_has_guard):
    committed = (("REVIEW.md", "the rules"), ("docs/INCIDENTS.md", "incidents and their plugs"),
                 (guard.GUARD_PATH, "the guard; " + ("the base branch's copy judges pushes" if base_has_guard
                                                     else "the base branch has none yet, so this checkout's runs")),
                 (guard.MERGED_PATH, "when one merged reviewer may take an Important push"))
    if wants_scanner(root):
        committed += ((guard.SCANNER_PATH, "the secret scan the guard runs (REVIEW.md says secrets:)"),)
    lines = []
    for path, what in committed:
        tracked = git("ls-files", "--error-unmatch", "--", path, check=False) is not None
        state = "missing" if not os.path.exists(os.path.join(root, path)) else "ok" if tracked else "uncommitted"
        lines.append("  %-11s %-44s %s" % (state, path, what))
    for full, what in ((bootstrap, "per clone: runs the base branch's guard"),
                       (guard.stamp_path(), "per clone: pass stamps")):
        lines.append("  %-11s %-44s %s" % ("ok" if os.path.exists(full) else "missing", os.path.relpath(full, root),
                                           what))
    return lines


def ahead_elsewhere(name, tip):
    """Notes for remotes whose copy of the base branch is ahead of the configured one, as in a fork whose origin is
    stale: pushes there are measured against old history."""
    branch, notes = name.split("/", 1)[-1], []
    for other in (git("remote", check=False) or "").split():
        sha = git("rev-parse", "--verify", "--quiet", "refs/remotes/%s/%s^{commit}" % (other, branch), check=False)
        if sha and sha != tip and git("merge-base", "--is-ancestor", tip, sha, check=False) is not None:
            notes.append("%s/%s is ahead of %s; if %s is the canonical repo, run `git config review-slices.base "
                         "%s/%s`" % (other, branch, name, other, other, branch))
    return notes


def cmd_doctor(_args):
    root, common, bootstrap = paths()
    problems, notes = [], []
    if guard.git_version() < (2, 32):
        problems.append("git %s is older than 2.32" % git("--version"))
    config = guard.working_config(root)
    if config is None:
        problems.append("no REVIEW.md at the repo root: copy the skill's templates/REVIEW.md")
    else:
        errors, warnings = guard.lint(config)
        problems += ["REVIEW.md: " + message for message in errors]
        notes += ["REVIEW.md: " + message for message in warnings]
        if config.get("secrets"):
            problems += [problem for problem in (scanner.preconditions(git, shutil.which("gitleaks")),) if problem]
            if not os.path.exists(os.path.join(root, guard.SCANNER_PATH)):
                problems.append("REVIEW.md says secrets: but %s is missing: run upgrade --apply" % guard.SCANNER_PATH)
        else:
            notes.append("secrets: not scanned (REVIEW.md has no secrets: line)")
    copy = read(os.path.join(root, guard.GUARD_PATH))
    if copy is None:
        problems.append("no %s: run install" % guard.GUARD_PATH)
    if not os.path.exists(os.path.join(root, guard.MERGED_PATH)):
        notes.append("no %s, so status always says three reviewers at important: run upgrade" % guard.MERGED_PATH)
    elif guard.source_version(copy) < guard.version_tuple(guard.VERSION):
        notes.append("the repo's guard is older than this skill's %s: run upgrade" % guard.VERSION)
    name, tip = guard.base_tip()
    base_rules = tip and guard.rules_at(tip)
    if (base_rules and base_rules.get("secrets") and guard.git_raw("show", "%s:%s" % (tip, guard.GUARD_PATH))
            and guard.git_raw("show", "%s:%s" % (tip, guard.SCANNER_PATH)) is None):
        problems.append("the base branch's REVIEW.md says secrets: but it has no %s, so every push is refused: "
                        "adding it there is the user's override" % guard.SCANNER_PATH)
    if not tip:
        problems.append("the base branch %s is not fetched in this clone" % name)
    elif config and config["base"] and name.split("/", 1)[-1] != config["base"]:
        notes.append("review-slices.base is %s but REVIEW.md's base is %s" % (name, config["base"]))
    else:
        notes = notes + ahead_elsewhere(name, tip)
    if read(bootstrap) != BOOTSTRAP:
        problems.append("the bootstrap is missing or out of date: run install --apply")
    wiring = guard.hook_wiring()
    if wiring is None:
        problems.append("this clone's pre-push does not reach the guard: run install")
    agent = []
    for relative, _matcher in AGENT_SETTINGS:
        try:
            agent = agent + ([relative] if has_agent_hook(agent_hook_entries(read(os.path.join(root, relative)))[1])
                             else [])
        except ValueError:
            problems.append("%s is not valid JSON" % relative)
    if read(os.path.join(root, AGENT_HOOK_PATH)) not in (None, read(SKILL_AGENT_HOOK)):
        notes.append("the repo's agent hook differs from this skill's: run upgrade")
    hooks_path = git("config", "--get", "core.hooksPath", check=False)
    print("review-slices doctor (skill %s, git %s)" % (guard.VERSION, ".".join(map(str, guard.git_version()))))
    print("hook: %s%s" % (wiring or "not wired", "; core.hooksPath=%s" % hooks_path if hooks_path else ""))
    print("base: %s%s" % (name, "" if tip else " (not fetched)"))
    print("agent hook: %s" % (", ".join(agent) if agent else "not set up (install --agent-hooks adds it)"))
    print("installed:")
    base_has_guard = bool(tip) and guard.git_raw("show", "%s:%s" % (tip, guard.GUARD_PATH)) is not None
    print("\n".join(tree_lines(root, bootstrap, base_has_guard)))
    for note in notes:
        print("note: " + note)
    for problem in problems:
        print("problem: " + problem)
    print("doctor: %s" % ("%d problem(s)" % len(problems) if problems else "ok"))
    return 1 if problems else 0


COMMANDS = {"install": cmd_install, "upgrade": cmd_upgrade, "doctor": cmd_doctor}


def main(argv):
    sys.stdout.reconfigure(errors="backslashreplace")  # paths that are not UTF-8 print escaped, never crash
    if len(argv) < 2 or argv[1] not in COMMANDS:
        print(__doc__, file=sys.stderr)
        return 2
    try:
        return COMMANDS[argv[1]](argv[2:])
    except (guard.GuardError, OSError, UnicodeError) as error:
        print("review-slices: %s" % error, file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
