#!/usr/bin/env python3
"""review-slices setup tools (skill version 0.3.0): install the guard in a clone, upgrade it, check the setup.

Run it from inside the target repo. It stays in the skill and is never copied into a repo.

    setup_tools.py install [--apply] [--hook-file]   wire this clone's pre-push to the guard committed on the base
                                                     branch; without --apply, print what would change and stop
    setup_tools.py upgrade [--apply]                 copy this skill's guard into .githooks/ when it is newer
    setup_tools.py doctor                            check this clone's setup; exit 1 on a problem

`install` never sets core.hooksPath. On git 2.54+ it registers a config hook, which runs beside .git/hooks, Husky
and pre-commit; --hook-file (and older git) writes a pre-push hook file instead, chaining any hook already there.
Standard library only, Python 3.8+, git 2.32+.
"""
import importlib.util
import os
import shlex
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SKILL_GUARD = os.path.join(HERE, "review_slices.py")
CHAINED = "pre-push.review-slices-chained"
WRAPPER_MARK = "# review-slices wrapper:"
PRE_COMMIT_MARK = "File generated by pre-commit"
BOOTSTRAP = '''#!/usr/bin/env python3
"""review-slices bootstrap, written into this clone by the skill's setup_tools.py install. It holds no rules: it
finds the guard committed on the base branch (git config review-slices.base) and runs it, so a fix to the guard
reaches every clone by push, and an edited working copy never judges its own push."""
import os
import subprocess
import sys
import tempfile

GUARD = ".githooks/review_slices.py"
OVERRIDE = "If the user decides to push anyway, the user runs `git push --no-verify`; an agent never does."


def git(*args):
    done = subprocess.run(("git",) + args, capture_output=True, text=True)
    return done.stdout if done.returncode == 0 else None


def find_guard():
    """(source, problem): the base branch's guard; no source and no problem means run the checkout's guard."""
    base = (git("config", "--get", "review-slices.base") or "").strip()
    if base and git("rev-parse", "--verify", "--quiet", "refs/remotes/%s^{commit}" % base):
        source = git("show", "refs/remotes/%s:%s" % (base, GUARD))
        if source:
            return source, None
        if git("cat-file", "-e", "refs/remotes/%s:REVIEW.md" % base) is not None:
            return None, "the base branch %s has REVIEW.md but no %s: restore the guard there" % (base, GUARD)
        return None, None  # adoption: the guard is not on the base branch yet
    remote = base.split("/", 1)[0] if base else "origin"
    if (git("for-each-ref", "--count=1", "refs/remotes/%s/" % remote) or "").strip():
        return None, ("the base branch %s is not in this clone: fetch it, or fix `git config review-slices.base`"
                      % (base or "(not set)"))
    return None, None  # a first push: the remote has nothing yet


def run(path, args, data):
    env = dict(os.environ, REVIEW_SLICES_HANDOFF="1")
    return subprocess.run([sys.executable, path] + args, input=data, env=env).returncode


def main(args):
    data = sys.stdin.buffer.read()
    source, problem = find_guard()
    if problem:
        print("review-slices refused the push: %s\\n%s" % (problem, OVERRIDE), file=sys.stderr)
        return 1
    if source is None:
        path = os.path.join((git("rev-parse", "--show-toplevel") or "").strip(), GUARD)
        if not os.path.isfile(path):
            print("review-slices: no guard on the base branch or in this checkout, so this push is not checked",
                  file=sys.stderr)
            return 0
        print("review-slices: the base branch has no guard yet, so this checkout's guard runs", file=sys.stderr)
        return run(path, args, data)
    with tempfile.TemporaryDirectory() as tmp:
        path = os.path.join(tmp, "review_slices.py")
        with open(path, "w", encoding="utf-8") as handle:
            handle.write(source)
        return run(path, args, data)


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
'''
WRAPPER = '''#!/bin/sh
# review-slices wrapper: run the guard, then the hook that was here before it (if any), each with the full input.
input=$(mktemp) || exit 1
trap 'rm -f "$input"' EXIT
cat > "$input"
python3 %s pre-push "$@" < "$input" || exit $?
next="$(dirname "$0")/%s"
if [ -x "$next" ]; then "$next" "$@" < "$input" || exit $?; fi
'''


def load_guard():
    spec = importlib.util.spec_from_file_location("review_slices", SKILL_GUARD)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


guard = load_guard()
git = guard.git


def read(path):
    try:
        with open(path, encoding="utf-8", errors="replace") as handle:
            return handle.read()
    except FileNotFoundError:
        return None


def write(path, text, mode=0o644):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as handle:
        handle.write(text)
    os.chmod(path, mode)


def paths():
    root = git("rev-parse", "--show-toplevel")
    common = git("rev-parse", "--path-format=absolute", "--git-common-dir")
    return root, common, os.path.join(common, "review-slices", "bootstrap.py")


def resolve_base(root):
    """The base branch's remote-tracking name (e.g. origin/main), from REVIEW.md's base and its tracking remote,
    else origin's default branch; None if neither is fetched."""
    config = guard.working_config(root)
    branch = config["base"] if config else "main"
    remote = git("config", "--get", "branch.%s.remote" % branch, check=False) or "origin"
    for name in ("%s/%s" % (remote, branch),
                 git("symbolic-ref", "--short", "--quiet", "refs/remotes/origin/HEAD", check=False)):
        if name and git("rev-parse", "--verify", "--quiet", "refs/remotes/%s^{commit}" % name, check=False):
            return name
    return None


def hook_file_steps(hooks, bootstrap):
    """Steps that wire a pre-push hook file in HOOKS to the bootstrap, keeping any hook already there."""
    pre_push = os.path.join(hooks, "pre-push")
    wrapper = WRAPPER % (shlex.quote(bootstrap), CHAINED)
    existing = read(pre_push)
    if existing is None or WRAPPER_MARK in existing:
        return [("write %s, which runs the bootstrap" % pre_push, lambda: write(pre_push, wrapper, 0o755))], []
    if PRE_COMMIT_MARK in existing:
        legacy = pre_push + ".legacy"
        current = read(legacy)
        if current is not None and WRAPPER_MARK not in current:
            return [], ["pre-commit manages %s and its .legacy hook is taken; ask the user how to chain them" % pre_push]
        return [("write %s, which pre-commit runs first with the full push input" % legacy,
                 lambda: write(legacy, wrapper, 0o755))], []
    chained = os.path.join(hooks, CHAINED)
    if os.path.exists(chained):
        return [], ["%s exists beside a pre-push hook that is not ours; ask the user" % chained]

    def chain():
        shutil.move(pre_push, chained)
        write(pre_push, wrapper, 0o755)
    return [("move the existing pre-push hook to %s and write a pre-push that runs the guard, then it, each with "
             "the full push input" % chained, chain)], []


def install_steps(hook_file):
    """(steps, problems): the (description, action) pairs `install` would carry out, and what blocks it."""
    root, common, bootstrap = paths()
    steps, problems = [], []
    if not os.path.exists(os.path.join(root, guard.GUARD_PATH)):
        steps.append(("copy the skill's guard %s to %s; commit it as a reviewed change" % (guard.VERSION,
                      guard.GUARD_PATH), lambda: write(os.path.join(root, guard.GUARD_PATH), read(SKILL_GUARD))))
    if read(bootstrap) != BOOTSTRAP:
        steps.append(("write %s, which runs the guard committed on the base branch" % bootstrap,
                      lambda: write(bootstrap, BOOTSTRAP, 0o755)))
    base = resolve_base(root)
    if base is None:
        problems.append("no remote-tracking base branch: fetch, then run install again (a first push is fine)")
    elif git("config", "--get", "review-slices.base", check=False) != base:
        steps.append(("set review-slices.base to %s" % base, lambda: git("config", "review-slices.base", base)))
    hooks_path = git("config", "--get", "core.hooksPath", check=False)
    if git("config", "--local", "--get", "core.hooksPath", check=False) == ".githooks":
        steps.append(("unset core.hooksPath=.githooks (0.1.0's install), so the hooks in .git/hooks run again",
                      lambda: git("config", "--local", "--unset", "core.hooksPath")))
        hooks_path = None
    command = "python3 %s pre-push" % shlex.quote(bootstrap)
    if not hook_file and guard.git_version() >= (2, 54):
        if (git("config", "--get", "hook.review-slices.command", check=False) != command
                or "pre-push" not in (git("config", "--get-all", "hook.review-slices.event", check=False) or "")):
            steps.append(("register the config hook review-slices for pre-push: %s" % command, lambda: (
                git("config", "--replace-all", "hook.review-slices.event", "pre-push"),
                git("config", "hook.review-slices.command", command))))
    elif hooks_path:
        problems.append("core.hooksPath is %s, so a hook file would go where another tool manages hooks; on git "
                        "2.54+ install registers a config hook beside it, else ask the user" % hooks_path)
    else:
        more_steps, more_problems = hook_file_steps(os.path.join(common, "hooks"), bootstrap)
        steps, problems = steps + more_steps, problems + more_problems
    return steps, problems


def cmd_install(args):
    steps, problems = install_steps("--hook-file" in args)
    apply = "--apply" in args
    print("review-slices install%s:" % ("" if apply else " (dry run; add --apply to make these changes)"))
    for number, (description, action) in enumerate(steps, 1):
        print("  %d. %s" % (number, description))
        if apply:
            action()
    if not steps:
        print("  nothing to change")
    for problem in problems:
        print("problem: " + problem)
    if apply:
        print()
        return max(cmd_doctor([]), 1 if problems else 0)
    return 1 if problems else 0


def cmd_upgrade(args):
    root, _common, _bootstrap = paths()
    copy = os.path.join(root, guard.GUARD_PATH)
    current = read(copy)
    if current is None:
        print("no %s here: run install first" % guard.GUARD_PATH)
        return 1
    have, skill = guard.source_version(current), guard.version_tuple(guard.VERSION)
    if current == read(SKILL_GUARD):
        print("the repo's guard is this skill's (%s)" % guard.VERSION)
        return 0
    if have > skill:
        print("the repo's guard (%s) is newer than this skill's (%s): update the skill instead" % (
            ".".join(map(str, have)), guard.VERSION))
        return 1
    print("copy this skill's guard (%s) over %s (%s)%s" % (guard.VERSION, guard.GUARD_PATH, ".".join(map(str, have)),
                                                         "" if "--apply" in args else "; add --apply to do it"))
    print("then commit it as a reviewed change (REVIEW.md puts it at important or higher); it judges pushes once it "
          "is on the base branch")
    if os.path.exists(os.path.join(root, ".githooks", "pre-push")):
        print("also delete .githooks/pre-push (0.1.0's hook) in that commit, once every clone has run install")
    if "--apply" in args:
        shutil.copy(SKILL_GUARD, copy)
    return 0


def tree_lines(root, common, bootstrap):
    entries = (("REVIEW.md", os.path.join(root, "REVIEW.md"), "the rules (committed)"),
               ("docs/INCIDENTS.md", os.path.join(root, "docs", "INCIDENTS.md"), "incidents and plugs (committed)"),
               (guard.GUARD_PATH, os.path.join(root, guard.GUARD_PATH), "the guard (committed; the base branch's "
                                                                          "copy judges pushes)"),
               (os.path.relpath(bootstrap, root), bootstrap, "per clone: runs the base branch's guard"),
               (os.path.relpath(guard.stamp_path(), root), guard.stamp_path(), "per clone: pass stamps"))
    return ["  %-8s %-44s %s" % ("ok" if os.path.exists(full) else "missing", shown, what)
            for shown, full, what in entries]


def cmd_doctor(_args):
    root, common, bootstrap = paths()
    problems, notes = [], []
    if guard.git_version() < (2, 32):
        problems.append("git %s is older than 2.32" % git("--version"))
    config = guard.working_config(root)
    if config is None:
        problems.append("no REVIEW.md at the repo root: copy the skill's templates/REVIEW.md")
    else:
        errors, warnings = guard.lint(config)
        problems += ["REVIEW.md: " + message for message in errors]
        notes += ["REVIEW.md: " + message for message in warnings]
    copy = read(os.path.join(root, guard.GUARD_PATH))
    if copy is None:
        problems.append("no %s: run install" % guard.GUARD_PATH)
    elif guard.source_version(copy) < guard.version_tuple(guard.VERSION):
        notes.append("the repo's guard is older than this skill's %s: run upgrade" % guard.VERSION)
    name, tip = guard.base_tip()
    if not tip:
        problems.append("the base branch %s is not fetched in this clone" % name)
    elif config and name.split("/", 1)[-1] != config["base"]:
        notes.append("review-slices.base is %s but REVIEW.md's base is %s" % (name, config["base"]))
    if read(bootstrap) != BOOTSTRAP:
        problems.append("the bootstrap is missing or out of date: run install --apply")
    wiring = guard.hook_wiring()
    if wiring is None:
        problems.append("this clone's pre-push does not reach the guard: run install")
    hooks_path = git("config", "--get", "core.hooksPath", check=False)
    print("review-slices doctor (skill %s, git %s)" % (guard.VERSION, ".".join(map(str, guard.git_version()))))
    print("hook: %s%s" % (wiring or "not wired", "; core.hooksPath=%s" % hooks_path if hooks_path else ""))
    print("base: %s%s" % (name, "" if tip else " (not fetched)"))
    print("installed:")
    print("\n".join(tree_lines(root, common, bootstrap)))
    for note in notes:
        print("note: " + note)
    for problem in problems:
        print("problem: " + problem)
    print("doctor: %s" % ("%d problem(s)" % len(problems) if problems else "ok"))
    return 1 if problems else 0


COMMANDS = {"install": cmd_install, "upgrade": cmd_upgrade, "doctor": cmd_doctor}


def main(argv):
    if len(argv) < 2 or argv[1] not in COMMANDS:
        print(__doc__, file=sys.stderr)
        return 2
    try:
        return COMMANDS[argv[1]](argv[2:])
    except guard.GuardError as error:
        print("review-slices: %s" % error, file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
