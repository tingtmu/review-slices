"""setup_tools.py: install wires a clone's pre-push to the guard on the base branch without breaking other hooks."""
import os
import unittest

from support import Repo, git_version

CONFIG_HOOKS = git_version() >= (2, 54)


def hook(path, body):
    with open(path, "w", encoding="utf-8") as handle:
        handle.write("#!/bin/sh\n" + body)
    os.chmod(path, 0o755)


class InstallTest(unittest.TestCase):
    def setUp(self):
        self.repo = Repo(self)
        self.hooks = self.repo.out("rev-parse", "--path-format=absolute", "--git-path", "hooks")

    def unreviewed_critical_change(self):
        self.repo.write("core/a.py")
        self.repo.commit("unreviewed")
        self.assertEqual(self.repo.run_suite().returncode, 0)

    def reviewed_critical_change(self):
        self.repo.write("core/b.py")
        self.repo.commit("reviewed", trailer=self.repo.trailer("critical"))
        self.assertEqual(self.repo.run_suite().returncode, 0)

    def test_a_dry_run_changes_nothing(self):
        done = self.repo.setup("install")
        self.assertEqual(done.returncode, 0, done.stdout)
        self.assertIn("dry run", done.stdout)
        self.assertIsNone(self.repo.git("config", "--get", "review-slices.base", check=False).stdout.strip() or None)
        self.assertFalse(os.path.exists(os.path.join(self.repo.path, ".git", "review-slices", "bootstrap.py")))

    @unittest.skipUnless(CONFIG_HOOKS, "config hooks need git 2.54+")
    def test_install_registers_a_config_hook_and_never_sets_hooks_path(self):
        repo = self.repo
        self.assertEqual(repo.setup("install", "--apply").returncode, 0)
        self.assertIn("bootstrap.py", repo.out("config", "--get", "hook.review-slices.command"))
        self.assertEqual(repo.git("config", "--get", "core.hooksPath", check=False).returncode, 1)
        self.assertEqual(repo.out("config", "--get", "review-slices.base"), "origin/main")
        self.unreviewed_critical_change()
        self.assertNotEqual(repo.try_push().returncode, 0)

    def test_a_hook_file_chains_an_existing_hook_that_drains_stdin(self):  # H5
        repo = self.repo
        marker = os.path.join(repo.tmp, "lfs-ran")
        hook(os.path.join(self.hooks, "pre-push"), "cat > '%s'\n" % marker)
        self.assertEqual(repo.setup("install", "--apply", "--hook-file").returncode, 0)
        self.assertTrue(os.path.exists(os.path.join(self.hooks, "pre-push.review-slices-chained")))
        self.unreviewed_critical_change()
        self.assertNotEqual(repo.try_push().returncode, 0)
        repo.git("reset", "-q", "--hard", "origin/main")
        self.reviewed_critical_change()
        done = repo.try_push()
        self.assertEqual(done.returncode, 0, done.stderr)
        with open(marker, encoding="utf-8") as handle:
            self.assertIn("refs/heads/main", handle.read())

    def test_beside_pre_commit_the_guard_is_its_legacy_hook(self):
        repo = self.repo
        hook(os.path.join(self.hooks, "pre-push"), "# File generated by pre-commit: https://pre-commit.com\n"
             'in=$(mktemp); cat > "$in"\nif [ -x "$0.legacy" ]; then "$0.legacy" "$@" < "$in" || exit 1; fi\n')
        self.assertEqual(repo.setup("install", "--apply", "--hook-file").returncode, 0)
        self.assertTrue(os.path.exists(os.path.join(self.hooks, "pre-push.legacy")))
        self.unreviewed_critical_change()
        self.assertNotEqual(repo.try_push().returncode, 0)

    def test_a_foreign_hooks_path_is_left_alone_without_config_hooks(self):
        repo = self.repo
        repo.git("config", "core.hooksPath", ".husky")
        done = repo.setup("install", "--apply", "--hook-file")
        self.assertNotEqual(done.returncode, 0)
        self.assertIn("core.hooksPath is .husky", done.stdout)
        self.assertEqual(repo.out("config", "--get", "core.hooksPath"), ".husky")

    @unittest.skipUnless(CONFIG_HOOKS, "config hooks need git 2.54+")
    def test_a_config_hook_runs_beside_a_foreign_hooks_path(self):
        repo = self.repo
        marker = os.path.join(repo.tmp, "husky-ran")
        os.makedirs(os.path.join(repo.path, ".husky"))
        hook(os.path.join(repo.path, ".husky", "pre-push"), "cat > '%s'\n" % marker)
        repo.git("config", "core.hooksPath", ".husky")
        self.assertEqual(repo.setup("install", "--apply").returncode, 0)
        self.unreviewed_critical_change()
        self.assertNotEqual(repo.try_push().returncode, 0)
        self.assertTrue(os.path.exists(marker))

    def test_install_moves_a_0_1_0_clone_off_hooks_path(self):
        repo = self.repo
        repo.write(".githooks/pre-push", '#!/bin/sh\nexec python3 "$(dirname "$0")/review_slices.py" pre-push "$@"\n')
        repo.commit("0.1.0's hook")
        repo.git("push", "-q", "origin", "main")
        repo.git("config", "core.hooksPath", ".githooks")
        done = repo.setup("install", "--apply")
        self.assertEqual(done.returncode, 0, done.stdout)
        self.assertEqual(repo.git("config", "--get", "core.hooksPath", check=False).returncode, 1)
        self.unreviewed_critical_change()
        self.assertNotEqual(repo.try_push().returncode, 0)

    def test_install_twice_changes_nothing_the_second_time(self):
        self.assertEqual(self.repo.setup("install", "--apply").returncode, 0)
        self.assertIn("nothing to change", self.repo.setup("install").stdout)


class BootstrapTest(unittest.TestCase):
    def setUp(self):
        self.repo = Repo(self)
        self.repo.install()

    def test_a_base_ref_that_vanished_is_refused(self):
        repo = self.repo
        repo.git("config", "review-slices.base", "origin/gone")
        repo.write("notes/n.md")
        repo.commit("notes")
        done = repo.try_push()
        self.assertNotEqual(done.returncode, 0)
        self.assertIn("fetch it", done.stderr)

    def test_a_base_branch_that_lost_its_guard_is_refused(self):
        repo = self.repo
        repo.git("rm", "-q", ".githooks/review_slices.py")
        repo.commit("drop the guard")
        repo.git("push", "-q", "--no-verify", "origin", "main")
        repo.write("notes/n.md")
        repo.commit("notes")
        done = repo.try_push()
        self.assertNotEqual(done.returncode, 0)
        self.assertIn("no .githooks/review_slices.py", done.stderr)

    def test_adoption_runs_the_checkout_guard(self):
        repo = Repo(self, rules=None, guard=False)
        repo.git("config", "review-slices.base", "origin/main")
        self.assertEqual(repo.setup("install", "--apply").returncode, 1)  # the guard copy is new: install says so
        self.repo = repo
        repo.write("REVIEW.md", "```review-slices\ntest: true\n```\n")
        repo.commit("adopt review-slices")
        self.assertEqual(repo.run_suite().returncode, 0)
        done = repo.try_push()
        self.assertNotEqual(done.returncode, 0, "REVIEW.md is at least important, so adoption needs a review")
        self.assertIn("this checkout's guard runs", done.stderr)


class UpgradeAndDoctorTest(unittest.TestCase):
    def test_upgrade_copies_a_newer_guard(self):
        repo = Repo(self)
        path = os.path.join(repo.path, ".githooks", "review_slices.py")
        with open(path, encoding="utf-8") as handle:
            source = handle.read()
        with open(path, "w", encoding="utf-8") as handle:
            handle.write(source.replace('VERSION = "', 'VERSION = "0.0.1"  # was "', 1))
        self.assertIn("add --apply", repo.setup("upgrade").stdout)
        self.assertEqual(repo.setup("upgrade", "--apply").returncode, 0)
        with open(path, encoding="utf-8") as handle:
            self.assertEqual(handle.read(), source)

    def test_doctor_names_an_unwired_clone(self):
        repo = Repo(self)
        done = repo.setup("doctor")
        self.assertEqual(done.returncode, 1)
        self.assertIn("does not reach the guard", done.stdout)

    def test_doctor_passes_after_install(self):
        repo = Repo(self)
        repo.install()
        done = repo.setup("doctor")
        self.assertEqual(done.returncode, 0, done.stdout)
        self.assertIn("bootstrap.py", done.stdout)


if __name__ == "__main__":
    unittest.main()
